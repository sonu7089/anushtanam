"""Deterministic bundled artwork export. Python 3 + Pillow 12.3.0/libwebp 1.6.0.

Run with --check in CI to verify committed resources/table byte for byte.
Masters and provenance stay in design/artwork, outside Android packaging.
"""
import argparse
import hashlib
import io
import json
import struct
from pathlib import Path

from PIL import Image, ImageCms, ImageOps, features
import PIL

ROOT = Path(__file__).resolve().parents[1]
DESIGN = ROOT / 'frontend/android/design/artwork'
RES = ROOT / 'frontend/android/src/main/res'
TABLE = ROOT / 'frontend/android/src/main/java/com/mantrasiddhi/presentation/components/ArtworkCatalog.kt'


def render(master, crop, edge, lossless):
    image = ImageOps.exif_transpose(master)
    if image.info.get('icc_profile'):
        alpha = image.getchannel('A') if 'A' in image.getbands() else None
        image = ImageCms.profileToProfile(image.convert('RGB'),
            ImageCms.ImageCmsProfile(io.BytesIO(image.info['icc_profile'])),
            ImageCms.createProfile('sRGB'), outputMode='RGB')
        if alpha is not None:
            image.putalpha(alpha)
    image = image.convert('RGBA' if 'A' in image.getbands() else 'RGB')
    if crop in ('square_end', 'banner_end'):
        ratio = 2 if crop == 'banner_end' else 1
        width = min(image.width, image.height * ratio)
        height = width // ratio
        image = image.crop((image.width-width, (image.height-height)//2,
                            image.width, (image.height+height)//2))
    image.thumbnail((edge, edge), Image.Resampling.LANCZOS)
    image.info.clear()
    return image


def webp(image, lossless):
    out = io.BytesIO()
    image.save(out, 'WEBP', lossless=lossless, quality=90, method=6, exact=True)
    data = out.getvalue()
    pos = 12
    while pos < len(data):
        kind, size = struct.unpack_from('<4sI', data, pos)
        assert kind not in (b'EXIF', b'XMP ', b'ICCP'), kind
        pos += 8 + size + size % 2
    return data


def generate(check):
    manifest = json.loads((DESIGN / 'manifest.json').read_text())
    assert PIL.__version__ == manifest['pillow']
    assert features.version('webp') == manifest['libwebp']
    outputs = {}
    rows = []
    kotlin = ['// Generated by scripts/generate-artwork.py. Do not edit.',
        'package com.mantrasiddhi.presentation.components', '',
        'import com.mantrasiddhi.R', '',
        'enum class AppArt { ' + ', '.join(a['id'] for a in manifest['assets']) + ' }',
        'enum class ArtUsage { Image, Thumbnail, Banner }',
        'data class ArtVariant(val resource: Int, val width: Int, val height: Int)',
        'internal fun artworkVariants(art: AppArt, usage: ArtUsage): List<ArtVariant> = when (art) {']
    for asset in manifest['assets']:
        path = DESIGN / 'masters' / asset['file']
        assert hashlib.sha256(path.read_bytes()).hexdigest() == asset['sha256'], path
        with Image.open(path) as master:
            assert list(master.size) == asset['size']
            groups = {}
            for usage, spec in asset['usages'].items():
                variants = []
                for edge in spec['edges']:
                    im = render(master, spec['crop'], edge, asset['alpha'])
                    name = f"art_{path.stem}_{usage}_{edge}"
                    data = webp(im, asset['alpha'])
                    with Image.open(io.BytesIO(data)) as decoded:
                        assert decoded.size == im.size
                        if asset['alpha']:
                            assert decoded.convert('RGBA').tobytes() == im.tobytes(), name
                    outputs[RES / 'drawable-nodpi' / (name + '.webp')] = data
                    variants.append(f'ArtVariant(R.drawable.{name}, {im.width}, {im.height})')
                    rows.append(dict(resource=name, width=im.width, height=im.height,
                                     sha256=hashlib.sha256(data).hexdigest(),
                                     bytes=len(data), alpha=asset['alpha'], lossless=asset['alpha']))
                groups[usage] = 'listOf(' + ', '.join(variants) + ')'
            body = groups['image']
            if 'thumb' in groups:
                body = f"if (usage == ArtUsage.Thumbnail) {groups['thumb']} else {body}"
            if 'banner' in groups:
                body = f"if (usage == ArtUsage.Banner) {groups['banner']} else {body}"
            kotlin.append(f"    AppArt.{asset['id']} -> {body}")
            if asset['id'] == 'EMBLEM':
                for density, edge in [('mdpi',108),('hdpi',162),('xhdpi',216),('xxhdpi',324),('xxxhdpi',432)]:
                    outputs[RES / f'drawable-{density}' / 'art_launcher.webp'] = webp(render(master, 'fit', edge, True), True)
    kotlin.append('}')
    outputs[TABLE] = ('\n'.join(kotlin)+'\n').encode()
    outputs[DESIGN / 'generated.json'] = (json.dumps(dict(
        manifestSha256=hashlib.sha256((DESIGN/'manifest.json').read_bytes()).hexdigest(),
        generatorSha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        variants=rows, files={
        str(p.relative_to(ROOT)).replace('\\', '/'): hashlib.sha256(data).hexdigest()
        for p, data in outputs.items()}), indent=2)+'\n').encode()
    actual = set(RES.glob('drawable*/art_*.webp'))
    expected = {p for p in outputs if p.suffix == '.webp'}
    assert not actual-expected, f'Stale derivatives: {actual-expected}'
    assert not list((RES / 'drawable-nodpi').glob('*.png')), 'Masters must stay outside res'
    for path, data in outputs.items():
        if check:
            assert path.exists() and path.read_bytes() == data, f'Regenerate {path}'
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(json.dumps(dict(resources=len(expected), bytes=sum(len(outputs[p]) for p in expected),
                          checked=check)))


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    generate(parser.parse_args().check)
